//! Rust definitions for the JSON Schema subset emitted by TypeBox.

use std::collections::BTreeMap;

use serde_json::{Map, Value};

const DERIVE: &str =
    "#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]\n";
/// Objects refuse fields they do not name, as the schema's
/// `additionalProperties: false` does.
const STRICT: &str = "#[serde(deny_unknown_fields)]\n";

/// Rust source with named definitions and object fields in sorted
/// order.
pub fn generate(schema: &Value) -> Result<String, String> {
    let definitions =
        schema["$defs"].as_object().ok_or("Schema lacks $defs")?;
    let mut uses = BTreeMap::new();
    for node in definitions.values() {
        collect_uses(node, definitions, &mut uses)?;
    }
    let omitted = uses
        .into_iter()
        .filter_map(|(name, contexts)| {
            let tag = contexts.first()?.as_ref()?;
            contexts
                .iter()
                .all(|context| context.as_ref() == Some(tag))
                .then(|| (name, tag.clone()))
        })
        .collect::<BTreeMap<_, _>>();
    let mut generator = Generator {
        definitions,
        omitted,
        constants: BTreeMap::new(),
        optional: false,
        output: String::from(
            r"// Generated by cargo run -p hamlet_protocol_gen. Do not edit.

#![allow(clippy::large_enum_variant)]

use serde::{Deserialize, Serialize};

",
        ),
    };
    for (name, node) in definitions {
        let omitted = generator
            .omitted
            .get(name)
            .cloned()
            .into_iter()
            .collect::<Vec<_>>();
        generator.definition(name, node, &omitted)?;
    }
    for (name, (kind, value)) in &generator.constants {
        generator.output.push_str(&format!(
            "/// The value of every `{}` field.\npub const {}: \
             {kind} = {value};\n\n",
            name.to_lowercase(),
            name
        ));
    }
    if generator.optional {
        generator.output.push_str(
            r"fn present<'de, D, T>(deserializer: D) -> std::result::Result<Option<T>, D::Error>
where
    D: serde::Deserializer<'de>,
    T: Deserialize<'de>,
{
    T::deserialize(deserializer).map(Some)
}
",
        );
    }
    Ok(generator.output)
}

struct Generator<'a> {
    definitions: &'a Map<String, Value>,
    omitted: BTreeMap<String, String>,
    /// The numeric literal fields, by name, with their type and
    /// value.
    constants: BTreeMap<String, (String, String)>,
    optional: bool,
    output: String,
}

impl Generator<'_> {
    fn definition(
        &mut self,
        name: &str,
        node: &Value,
        omitted: &[String],
    ) -> Result<(), String> {
        let start = self.output.len();
        let declaration = if let Some(values) = fixed(node) {
            let variants = values
                .iter()
                .map(|wire| {
                    format!(
                        "    #[serde(rename = {wire:?})]\n    {},\n",
                        pascal(wire)
                    )
                })
                .collect::<String>();
            format!("{DERIVE}pub enum {name} {{\n{variants}}}\n\n")
        } else if node["type"] == "object"
            && node.get("patternProperties").is_none()
        {
            let fields =
                self.fields(name, node, omitted, "    ", "pub ")?;
            format!(
                "{DERIVE}{STRICT}pub struct {name} \
                 {{\n{fields}}}\n\n"
            )
        } else if node.get("anyOf").is_some()
            && nullable(node).is_none()
        {
            let members = members(node, self.definitions)?;
            self.union(name, &members, omitted)?
        } else {
            let kind = self.kind(&format!("{name}Value"), node)?;
            format!("pub type {name} = {kind};\n\n")
        };
        let nested = self.output.split_off(start);
        self.output.push_str(&declaration);
        self.output.push_str(&nested);
        Ok(())
    }

    fn fields(
        &mut self,
        parent: &str,
        node: &Value,
        omitted: &[String],
        indent: &str,
        visibility: &str,
    ) -> Result<String, String> {
        let properties = node["properties"]
            .as_object()
            .ok_or_else(|| format!("{parent} lacks properties"))?;
        let mut output = String::new();
        for (wire, schema) in properties {
            if omitted.contains(wire) {
                continue;
            }
            let name = snake(wire);
            let mut kind = self
                .kind(&format!("{parent}{}", pascal(wire)), schema)?;
            if let Some(value) = schema["const"].as_number() {
                let constant = (kind.clone(), value.to_string());
                let previous = self
                    .constants
                    .insert(name.to_uppercase(), constant.clone());
                if previous
                    .is_some_and(|previous| previous != constant)
                {
                    return Err(format!(
                        "The `{wire}` fields hold different literals"
                    ));
                }
            }
            if name != *wire {
                output.push_str(&format!(
                    "{indent}#[serde(rename = {wire:?})]\n"
                ));
            }
            if required(node, wire) {
                if nullable(schema).is_some() {
                    // Serde reads a missing `Option` as `None` unless
                    // the field has its own deserializer.
                    output.push_str(&format!(
                        "{indent}#[serde(deserialize_with = \
                         \"Option::deserialize\")]\n"
                    ));
                }
            } else {
                kind = format!("Option<{kind}>");
                output.push_str(&format!(
                    "{indent}#[serde(default, skip_serializing_if = \
                     \"Option::is_none\")]\n"
                ));
                // A null where the schema does not take one is
                // refused, as a missing nullable field is above.
                self.optional = true;
                output.push_str(&format!(
                    "{indent}#[serde(deserialize_with = \
                     \"present\")]\n"
                ));
            }
            output.push_str(&format!(
                "{indent}{visibility}{name}: {kind},\n"
            ));
        }
        Ok(output)
    }

    fn kind(
        &mut self,
        name: &str,
        node: &Value,
    ) -> Result<String, String> {
        if let Some(reference) = reference(node) {
            if !self.definitions.contains_key(reference) {
                return Err(format!("Unknown reference {reference}"));
            }
            return Ok(reference.into());
        }
        if let Some(inner) = nullable(node) {
            return Ok(format!(
                "Option<{}>",
                self.kind(name, inner)?
            ));
        }
        if node.as_object().is_some_and(|object| object.is_empty()) {
            return Ok("serde_json::Value".into());
        }
        if let Some(patterns) = node["patternProperties"].as_object()
        {
            if patterns.len() != 1 {
                return Err(format!("Unsupported record {name}"));
            }
            let value =
                self.kind(name, patterns.values().next().unwrap())?;
            return Ok(format!(
                "std::collections::BTreeMap<String, {value}>"
            ));
        }
        if fixed(node).is_some() || node.get("anyOf").is_some() {
            self.definition(name, node, &[])?;
            return Ok(name.into());
        }
        let whole = node["type"] == "integer"
            || node["const"]
                .as_f64()
                .is_some_and(|n| n.fract() == 0.0);
        let natural =
            node["minimum"].as_f64().is_some_and(|m| m >= 0.0)
                || node["const"].as_f64().is_some_and(|n| n >= 0.0);
        match node["type"].as_str() {
            Some("string") => Ok("String".into()),
            Some("integer" | "number") if whole && natural => {
                Ok("u64".into())
            }
            Some("integer" | "number") if whole => Ok("i64".into()),
            Some("number") => Ok("f64".into()),
            Some("null") => Ok("()".into()),
            Some("boolean") => Ok("bool".into()),
            Some("array") => Ok(format!(
                "Vec<{}>",
                self.kind(name, &node["items"])?
            )),
            Some("object") => {
                self.definition(name, node, &[])?;
                Ok(name.into())
            }
            _ => {
                Err(format!("Unsupported schema for {name}: {node}"))
            }
        }
    }

    fn union(
        &mut self,
        name: &str,
        members: &[Member],
        omitted: &[String],
    ) -> Result<String, String> {
        let mut variants = String::new();
        let attribute;
        if let Some(tag) = tag(members, omitted) {
            attribute = format!(
                "#[serde(tag = {tag:?}, deny_unknown_fields)]"
            );
            let mut groups = Vec::<(String, Vec<Member>)>::new();
            for member in members {
                for value in
                    fixed(&member.node["properties"][&tag]).unwrap()
                {
                    if let Some((_, group)) = groups
                        .iter_mut()
                        .find(|(wire, _)| *wire == value)
                    {
                        group.push(member.clone());
                    } else {
                        groups.push((value, vec![member.clone()]));
                    }
                }
            }
            let mut omitted = omitted.to_vec();
            omitted.push(tag.clone());
            for (wire, group) in groups {
                let variant = pascal(&wire);
                variants.push_str(&format!(
                    "    #[serde(rename = {wire:?})]\n"
                ));
                let payload =
                    group[0].origin.as_ref().filter(|origin| {
                        self.omitted.get(*origin) == Some(&tag)
                            && group.iter().all(|member| {
                                member.origin.as_ref()
                                    == Some(*origin)
                            })
                    });
                if let Some(payload) = payload {
                    variants.push_str(&format!(
                        "    {variant}({payload}),\n"
                    ));
                } else if group.len() == 1 {
                    variants.push_str(&self.variant(
                        name,
                        &variant,
                        &group[0].node,
                        &omitted,
                    )?);
                } else {
                    let inner = format!("{name}{variant}");
                    let declaration =
                        self.union(&inner, &group, &omitted)?;
                    self.output.push_str(&declaration);
                    variants.push_str(&format!(
                        "    {variant}({inner}),\n"
                    ));
                }
            }
        } else {
            attribute =
                "#[serde(untagged, deny_unknown_fields)]".into();
            for (index, member) in members.iter().enumerate() {
                let field = member.node["required"]
                    .as_array()
                    .and_then(|fields| {
                        fields.iter().filter_map(Value::as_str).find(
                            |field| {
                                !omitted
                                    .iter()
                                    .any(|tag| tag == field)
                                    && members.iter().enumerate().all(
                                        |(other, member)| {
                                            other == index
                                                || member.node
                                                    ["properties"]
                                                    .get(*field)
                                                    .is_none()
                                        },
                                    )
                            },
                        )
                    })
                    .ok_or_else(|| {
                        format!(
                            "Union {name} has a member without a \
                             distinguishing required field"
                        )
                    })?;
                variants.push_str(&self.variant(
                    name,
                    &pascal(field),
                    &member.node,
                    omitted,
                )?);
            }
        }
        Ok(format!(
            "{DERIVE}{attribute}\npub enum {name} \
             {{\n{variants}}}\n\n"
        ))
    }

    fn variant(
        &mut self,
        parent: &str,
        variant: &str,
        node: &Value,
        omitted: &[String],
    ) -> Result<String, String> {
        let fields = self.fields(
            &format!("{parent}{variant}"),
            node,
            omitted,
            "        ",
            "",
        )?;
        Ok(format!("    {variant} {{\n{fields}    }},\n"))
    }
}

#[derive(Clone)]
struct Member {
    node: Value,
    origin: Option<String>,
}

fn members(
    node: &Value,
    definitions: &Map<String, Value>,
) -> Result<Vec<Member>, String> {
    fn flatten(
        node: &Value,
        definitions: &Map<String, Value>,
        path: &mut Vec<String>,
        origin: Option<&str>,
        output: &mut Vec<Member>,
    ) -> Result<(), String> {
        if let Some(name) = reference(node) {
            if path.iter().any(|parent| parent == name) {
                return Err(format!("Recursive union {name}"));
            }
            let node = definitions
                .get(name)
                .ok_or_else(|| format!("Unknown reference {name}"))?;
            path.push(name.into());
            flatten(
                node,
                definitions,
                path,
                origin.or(Some(name)),
                output,
            )?;
            path.pop();
        } else if let Some(children) = node["anyOf"].as_array() {
            for child in children {
                flatten(child, definitions, path, origin, output)?;
            }
        } else if node["type"] == "object"
            && node.get("properties").is_some()
        {
            output.push(Member {
                node: node.clone(),
                origin: origin.map(str::to_owned),
            });
        } else {
            return Err(format!(
                "Union member is not an object: {node}"
            ));
        }
        Ok(())
    }
    let mut output = Vec::new();
    flatten(node, definitions, &mut Vec::new(), None, &mut output)?;
    Ok(output)
}

fn collect_uses(
    node: &Value,
    definitions: &Map<String, Value>,
    uses: &mut BTreeMap<String, Vec<Option<String>>>,
) -> Result<(), String> {
    if let Some(name) = reference(node) {
        uses.entry(name.into()).or_default().push(None);
    } else if let Some(children) = node["anyOf"]
        .as_array()
        .filter(|_| nullable(node).is_none())
    {
        let tag = tag(&members(node, definitions)?, &[]);
        for child in children {
            if let Some(name) = reference(child) {
                let context = if let Some(tag) = &tag {
                    let members = members(child, definitions)?;
                    let values = members
                        .iter()
                        .flat_map(|member| {
                            fixed(&member.node["properties"][tag])
                                .unwrap()
                        })
                        .collect::<Vec<_>>();
                    values
                        .iter()
                        .all(|value| value == &values[0])
                        .then(|| tag.clone())
                } else {
                    None
                };
                uses.entry(name.into()).or_default().push(context);
            } else {
                collect_uses(child, definitions, uses)?;
            }
        }
    } else {
        match node {
            Value::Object(object) => {
                for child in object.values() {
                    collect_uses(child, definitions, uses)?;
                }
            }
            Value::Array(array) => {
                for child in array {
                    collect_uses(child, definitions, uses)?;
                }
            }
            _ => {}
        }
    }
    Ok(())
}

fn tag(members: &[Member], omitted: &[String]) -> Option<String> {
    members.first()?.node["properties"]
        .as_object()?
        .keys()
        .find(|field| {
            if omitted.contains(field) {
                return false;
            }
            let values = members
                .iter()
                .map(|member| {
                    required(&member.node, field)
                        .then(|| {
                            fixed(&member.node["properties"][*field])
                        })
                        .flatten()
                })
                .collect::<Option<Vec<_>>>();
            values.is_some_and(|values| {
                let values =
                    values.into_iter().flatten().collect::<Vec<_>>();
                values.iter().any(|value| value != &values[0])
            })
        })
        .cloned()
}

fn reference(node: &Value) -> Option<&str> {
    node["$ref"].as_str()?.strip_prefix("#/$defs/")
}

fn fixed(node: &Value) -> Option<Vec<String>> {
    if let Some(value) = node["const"].as_str() {
        return Some(vec![value.into()]);
    }
    node["enum"]
        .as_array()?
        .iter()
        .map(|value| value.as_str().map(str::to_owned))
        .collect()
}

fn nullable(node: &Value) -> Option<&Value> {
    let members = node["anyOf"].as_array()?;
    if members.len() != 2 {
        return None;
    }
    match (members[0]["type"] == "null", members[1]["type"] == "null")
    {
        (true, false) => Some(&members[1]),
        (false, true) => Some(&members[0]),
        _ => None,
    }
}

fn required(node: &Value, field: &str) -> bool {
    node["required"].as_array().is_some_and(|fields| {
        fields.iter().any(|value| value == field)
    })
}

fn snake(wire: &str) -> String {
    let mut name = String::new();
    for ch in wire.chars() {
        if ch.is_ascii_uppercase() {
            if !name.is_empty() {
                name.push('_');
            }
            name.push(ch.to_ascii_lowercase());
        } else {
            name.push(ch);
        }
    }
    if matches!(
        name.as_str(),
        "as" | "async"
            | "await"
            | "break"
            | "const"
            | "continue"
            | "crate"
            | "dyn"
            | "else"
            | "enum"
            | "extern"
            | "false"
            | "fn"
            | "for"
            | "gen"
            | "if"
            | "impl"
            | "in"
            | "let"
            | "loop"
            | "match"
            | "mod"
            | "move"
            | "mut"
            | "pub"
            | "ref"
            | "return"
            | "self"
            | "static"
            | "struct"
            | "super"
            | "trait"
            | "true"
            | "type"
            | "unsafe"
            | "use"
            | "where"
            | "while"
            | "abstract"
            | "become"
            | "box"
            | "do"
            | "final"
            | "macro"
            | "override"
            | "priv"
            | "typeof"
            | "unsized"
            | "virtual"
            | "yield"
            | "try"
    ) {
        name.push('_');
    }
    name
}

fn pascal(wire: &str) -> String {
    match wire {
        " " => return "Space".into(),
        "+" => return "Plus".into(),
        "-" => return "Minus".into(),
        _ => {}
    }
    wire.split(|ch: char| !ch.is_ascii_alphanumeric())
        .filter(|word| !word.is_empty())
        .map(|word| {
            let mut chars = word.chars();
            format!(
                "{}{}",
                chars.next().unwrap().to_ascii_uppercase(),
                chars.as_str()
            )
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use serde_json::json;

    use super::generate;

    #[test]
    fn definitions_and_fields_are_sorted_independently_of_schema_order()
     {
        let first = serde_json::from_str::<serde_json::Value>(r#"{
            "$defs": {
                "Zed": {"type": "object", "required": ["z", "a"], "properties": {
                    "z": {"type": "integer"}, "a": {"type": "string"}
                }},
                "Alpha": {"type": "boolean"}
            }
        }"#).unwrap();
        let second = serde_json::from_str::<serde_json::Value>(r#"{
            "$defs": {
                "Alpha": {"type": "boolean"},
                "Zed": {"type": "object", "required": ["z", "a"], "properties": {
                    "a": {"type": "string"}, "z": {"type": "integer"}
                }}
            }
        }"#).unwrap();
        let source = generate(&first).unwrap();
        assert_eq!(source, generate(&second).unwrap());
        assert!(
            source.find("pub type Alpha").unwrap()
                < source.find("pub struct Zed").unwrap()
        );
        assert!(source.contains("pub a: String,\n    pub z: i64,"));
        assert!(source.contains(
            "#[serde(deny_unknown_fields)]\npub struct Zed"
        ));
    }

    #[test]
    fn nullable_fields_stay_null_and_optional_fields_are_omitted() {
        let source = generate(&json!({"$defs": {"Document": {
            "type": "object", "required": ["text", "at"], "properties": {
                "text": {"anyOf": [{"type": "string"}, {"type": "null"}]},
                "reflectEvery": {"type": "integer"},
                "at": {"type": "integer", "minimum": 0}
            }
        }}})).unwrap();
        assert!(source.contains("pub at: u64"));
        assert!(
            source.contains(
                "#[serde(deserialize_with = \
                 \"Option::deserialize\")]\n    pub text: \
                 Option<String>"
            )
        );
        assert!(source.contains(
            "#[serde(default, skip_serializing_if = \
             \"Option::is_none\")]\n    #[serde(deserialize_with = \
             \"present\")]\n    pub reflect_every: Option<i64>"
        ));
        assert!(
            source.contains("#[serde(rename = \"reflectEvery\")]")
        );
    }
    #[test]
    fn records_unknowns_enums_and_keywords_keep_their_wire_names() {
        let source = generate(&json!({"$defs": {
            "Doing": {"enum": ["read-file", " ", "+", "-"]},
            "Agent": {"type": "object", "required": ["ref", "values", "data", "activity"], "properties": {
                "ref": {"type": "string"},
                "values": {"type": "object", "patternProperties": {"^.*$": {"type": "boolean"}}},
                "data": {},
                "activity": {"type": "object", "required": ["step"], "properties": {"step": {"type": "integer"}}}
            }}
        }})).unwrap();
        for (wire, variant) in [
            ("read-file", "ReadFile"),
            (" ", "Space"),
            ("+", "Plus"),
            ("-", "Minus"),
        ] {
            assert!(source.contains(&format!(
                "#[serde(rename = {wire:?})]\n    {variant},"
            )));
        }
        assert!(source.contains(
            "#[serde(rename = \"ref\")]\n    pub ref_: String"
        ));
        assert!(source.contains(
            "pub values: std::collections::BTreeMap<String, bool>"
        ));
        assert!(source.contains("pub data: serde_json::Value"));
        assert!(source.contains("pub activity: AgentActivity"));
        assert!(source.contains("pub struct AgentActivity"));
        assert!(
            source.find("pub struct Agent").unwrap()
                < source.find("pub enum Doing").unwrap()
        );
    }

    #[test]
    fn tagged_unions_keep_nested_tags_and_group_shared_values() {
        let source = generate(&json!({"$defs": {
            "Hello": {"type": "object", "required": ["type", "v"], "properties": {
                "type": {"const": "hello", "type": "string"}, "v": {"const": 0, "type": "integer"}
            }},
            "Edit": {"anyOf": [
                {"type": "object", "required": ["type", "doc", "text"], "properties": {
                    "type": {"const": "edit"}, "doc": {"enum": ["character", "notes"]}, "text": {"type": "string"}
                }},
                {"type": "object", "required": ["type", "doc", "set"], "properties": {
                    "type": {"const": "edit"}, "doc": {"const": "limits"}, "set": {}
                }},
                {"type": "object", "required": ["type", "doc", "whole"], "properties": {
                    "type": {"const": "edit"}, "doc": {"const": "limits"}, "whole": {}
                }}
            ]},
            "ClientMessage": {"anyOf": [{"$ref": "#/$defs/Hello"}, {"$ref": "#/$defs/Edit"}]}
        }})).unwrap();
        for expected in [
            "#[serde(tag = \"type\", deny_unknown_fields)]",
            "Hello(Hello)",
            "Edit(Edit)",
            "pub v: u64",
            "pub const V: u64 = 0;",
            "#[serde(tag = \"doc\", deny_unknown_fields)]",
            "Character {",
            "Notes {",
            "Limits(EditLimits)",
            "#[serde(untagged, deny_unknown_fields)]\npub enum \
             EditLimits",
            "Set {",
            "Whole {",
        ] {
            assert!(
                source.contains(expected),
                "Missing {expected}:\n{source}"
            );
        }
        assert!(!source.contains("pub type_:"));
        assert!(!source.contains("type_:"));
    }

    #[test]
    fn null_only_fields_require_json_null() {
        let source = generate(&json!({"$defs": {"Nothing": {"type": "object", "required": ["danger"], "properties": {"danger": {"type": "null"}}}}})).unwrap();
        assert!(source.contains("pub danger: ()"));
    }

    #[test]
    fn ambiguous_untagged_unions_name_the_union_in_the_error() {
        let error = generate(&json!({"$defs": {"Ambiguous": {"anyOf": [
            {"type": "object", "required": ["text"], "properties": {"text": {"type": "string"}}},
            {"type": "object", "required": ["text"], "properties": {"text": {"type": "integer"}}}
        ]}}})).unwrap_err();
        assert!(error.contains("Union Ambiguous"), "{error}");
        assert!(
            error.contains("distinguishing required field"),
            "{error}"
        );
    }
}
