use std::fmt::Write;
use std::path::Path;

use diesel::prelude::*;
use diesel::sql_types::{BigInt, Text};
use hamlet_testing::Scratch;
use regex::Regex;

use super::Store;

/// The schema module, from the crate's root.
const SCHEMA_RS: &str = "src/schema.rs";

#[derive(QueryableByName)]
struct Table {
    #[diesel(sql_type = Text)]
    name: String,
    #[diesel(sql_type = Text)]
    sql: String,
}

#[derive(QueryableByName)]
struct Column {
    #[diesel(sql_type = Text)]
    name: String,
    #[diesel(sql_type = Text)]
    r#type: String,
    #[diesel(sql_type = BigInt)]
    notnull: i64,
    #[diesel(sql_type = BigInt)]
    pk: i64,
}

#[derive(QueryableByName)]
struct ForeignKey {
    #[diesel(sql_type = BigInt)]
    id: i64,
    #[diesel(sql_type = Text)]
    table: String,
    #[diesel(sql_type = Text)]
    from: String,
    #[diesel(sql_type = Text)]
    to: String,
}

fn columns_of(db: &mut SqliteConnection, table: &str) -> Vec<Column> {
    diesel::sql_query(
        "SELECT name, type, \"notnull\", pk FROM \
         pragma_table_info(?)",
    )
    .bind::<Text, _>(table)
    .load(db)
    .unwrap()
}

/// The column's name in Rust, which may not be a keyword.
fn field(name: &str) -> String {
    if name == "type" {
        format!("{name}_")
    } else {
        name.to_owned()
    }
}

/// `schema.rs` for the tables of `db`.
fn module(db: &mut SqliteConnection) -> String {
    let tables = diesel::sql_query(
        "SELECT name, sql FROM sqlite_schema WHERE type = 'table' \
         ORDER BY name",
    )
    .load::<Table>(db)
    .unwrap();
    let mut out = String::from(
        "// Generated by `cargo test -p hamlet_server` from the \
         store's schema. Do not edit.\n\n",
    );
    let mut joins = String::new();
    for table in &tables {
        let columns = columns_of(db, &table.name);
        let mut keys =
            columns.iter().filter(|c| c.pk > 0).collect::<Vec<_>>();
        keys.sort_by_key(|c| c.pk);
        assert!(
            !keys.is_empty(),
            "{} has no primary key",
            table.name
        );
        let keys = keys
            .iter()
            .map(|c| field(&c.name))
            .collect::<Vec<_>>()
            .join(", ");
        writeln!(
            out,
            "diesel::table! {{\n    {} ({keys}) {{",
            table.name
        )
        .unwrap();
        for column in &columns {
            let name = regex::escape(&column.name);
            let boolean = Regex::new(&format!(
                r"\b{name}\b INTEGER[^,\n]*CHECK \(({name} IS NULL OR )?{name} IN \(0, 1\)\)"
            ))
            .unwrap()
            .is_match(&table.sql);
            let base = match column.r#type.as_str() {
                _ if boolean => "Bool",
                "INTEGER" => "BigInt",
                "TEXT" => "Text",
                "BLOB" => "Binary",
                "REAL" => "Double",
                other => panic!("no Diesel type for {other}"),
            };
            let kind = if column.notnull != 0 || column.pk > 0 {
                base.to_owned()
            } else {
                format!("Nullable<{base}>")
            };
            if field(&column.name) != column.name {
                writeln!(
                    out,
                    "        #[sql_name = \"{}\"]",
                    column.name
                )
                .unwrap();
            }
            writeln!(
                out,
                "        {} -> {kind},",
                field(&column.name)
            )
            .unwrap();
        }
        out.push_str("    }\n}\n\n");
        let keys = diesel::sql_query(
            "SELECT id, \"table\", \"from\", \"to\" FROM \
             pragma_foreign_key_list(?) ORDER BY \"table\", id",
        )
        .bind::<Text, _>(&table.name)
        .load::<ForeignKey>(db)
        .unwrap();
        let mut parents = Vec::<(&str, Vec<&str>)>::new();
        for key in &keys {
            let single =
                keys.iter().filter(|k| k.id == key.id).count() == 1;
            let target = columns_of(db, &key.table)
                .into_iter()
                .filter(|c| c.pk > 0)
                .map(|c| c.name)
                .collect::<Vec<_>>();
            if !single
                || target != [key.to.as_str()]
                || key.table == table.name
            {
                continue;
            }
            match parents.iter_mut().find(|(p, _)| *p == key.table) {
                Some((_, from)) => from.push(&key.from),
                None => parents.push((&key.table, vec![&key.from])),
            }
        }
        for (parent, mut from) in parents {
            // Diesel allows one join per pair of tables: the plain
            // `binding` column when there are several, else none.
            if from.len() > 1 {
                from.retain(|f| *f == "binding");
            }
            if let [from] = from[..] {
                writeln!(
                    joins,
                    "diesel::joinable!({} -> {parent} ({from}));",
                    table.name
                )
                .unwrap();
            }
        }
    }
    out.push_str(&joins);
    out.push_str(
        "\ndiesel::allow_tables_to_appear_in_same_query!(\n",
    );
    for table in &tables {
        writeln!(out, "    {},", table.name).unwrap();
    }
    out.push_str(");\n");
    out
}

#[test]
fn the_schema_module_is_current() {
    let dir = Scratch::new("server-schema");
    let mut store = Store::open(&dir.join("realm.sqlite")).unwrap();
    let expected = module(store.connection());
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join(SCHEMA_RS);
    // A Windows checkout may end its lines with CRLF.
    if std::fs::read_to_string(&path)
        .is_ok_and(|kept| kept.replace("\r\n", "\n") == expected)
    {
        return;
    }
    std::fs::write(&path, expected).unwrap();
    panic!(
        "{SCHEMA_RS} was stale and is regenerated from the store's \
         schema; commit it."
    );
}
