//! Currency of the runtime protocol's schema that the pi harness
//! validates messages against.

use std::path::Path;

use hamlet_protocol::runtime::{RuntimeMessage, ServerMessage};
use schemars::generate::SchemaSettings;
use serde_json::json;

/// The pi harness's copy of the schema, from the repository's root.
const PI_SCHEMA: &str = "harnesses/pi/src/protocol-schema.ts";

/// The runtime protocol as a TypeScript module exporting its JSON
/// Schema.
fn module() -> String {
    // The serialize contract keeps a field that is written as `null`
    // required, the way the server sends it.
    let mut generator = SchemaSettings::draft2020_12()
        .for_serialize()
        .into_generator();
    let server = generator.subschema_for::<ServerMessage>();
    let runtime = generator.subschema_for::<RuntimeMessage>();
    let schema = json!({
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "title": "Hamlet runtime protocol",
        "anyOf": [server, runtime],
        "$defs": generator.take_definitions(true),
    });
    let mut json = Vec::new();
    let formatter =
        serde_json::ser::PrettyFormatter::with_indent(b"    ");
    let mut serializer =
        serde_json::Serializer::with_formatter(&mut json, formatter);
    serde::Serialize::serialize(&schema, &mut serializer).unwrap();
    format!(
        "// Generated by `cargo test -p hamlet_protocol` from\n// \
         crates/hamlet_protocol/src/runtime/. Do not \
         edit.\n\nexport const schema = {} as const;\n",
        String::from_utf8(json).unwrap()
    )
}

#[test]
fn the_pi_harness_has_the_current_schema() {
    let path = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .join(PI_SCHEMA);
    let expected = module();
    if std::fs::read_to_string(&path).ok().as_deref()
        == Some(&expected)
    {
        return;
    }
    std::fs::write(&path, expected).unwrap();
    panic!(
        "{PI_SCHEMA} was stale and is regenerated from the runtime \
         protocol's types; commit it."
    );
}
